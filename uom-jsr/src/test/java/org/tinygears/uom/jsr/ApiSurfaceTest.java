/**
 * Pins the public API of the modules (docs/DESIGN.md, section 8) to docs/api/public-api.txt; {@code -Duom.writeApi} rewrites the
 * file. Each module is read from the class path entry of one of its classes (uom-engine and uom from the reactor
 * or ~/.m2).
 */
class ApiSurfaceTest {
    private static final Path FILE = Path.of("../docs/api/public-api.txt");
    private static final String HEADER = """
            # The public API of uom (docs/DESIGN.md, section 8): one sorted line per module directive, public type and public or
            # protected member in an exported package; "hidden" lines are public types of other packages, not API.
            # Generated by ApiSurfaceTest; rewrite with: mvn -B verify -Duom.writeApi
            """;

    @Test
    void matchesPinnedApi() throws Exception {
        List<String> actual = new ArrayList<>();
        actual.addAll(surface(module(Factor.class)));
        actual.addAll(surface(module(org.tinygears.uom.Quantity.class)));
        actual.addAll(surface(module(UomUnit.class)));
        if (System.getProperty("uom.writeApi") != null) {
            Files.createDirectories(FILE.getParent());
            Files.writeString(FILE, HEADER + String.join("\n", actual) + "\n", StandardCharsets.UTF_8);
        }
        List<String> pinned = Files.readAllLines(FILE, StandardCharsets.UTF_8).stream()
                .filter(l -> !l.isEmpty() && !l.startsWith("#")).toList();
        List<String> added = actual.stream().filter(l -> !pinned.contains(l)).toList();
        List<String> removed = pinned.stream().filter(l -> !actual.contains(l)).toList();
        assertTrue(
                added.isEmpty() && removed.isEmpty(),
                "API differs from " + FILE + " (see docs/DESIGN.md, section 8)\nadded:\n  " + String.join("\n  ", added)
                        + "\nremoved:\n  " + String.join("\n  ", removed));
        assertEquals(pinned, actual);
    }

    @Test
    void helperPackagesAreExportedToTheTwoApisOnly() throws Exception {
        ModuleReference jsr = module(UomUnit.class);
        assertEquals(
                Set.of("org.tinygears.uom.jsr", "org.tinygears.uom.jsr.quantity", "org.tinygears.uom.jsr.systems"),
                jsr.descriptor().exports().stream().map(ModuleDescriptor.Exports::source).collect(Collectors.toSet()));
        // spi, the hook the provider implements, is internal to the module
        assertTrue(jsr.descriptor().exports().stream().noneMatch(ModuleDescriptor.Exports::isQualified));
        assertTrue(jsr.descriptor().packages().contains("org.tinygears.uom.jsr.spi"));
        assertTrue(jsr.descriptor().opens().isEmpty());
        assertEquals(jsr, module(UomServiceProvider.class));
        ModuleReference uom = module(org.tinygears.uom.Quantity.class);
        Set<String> api = Set.of("org.tinygears.uom", "org.tinygears.uom.quantity", "org.tinygears.uom.systems");
        assertEquals(
                api,
                uom.descriptor().exports().stream().filter(e -> !e.isQualified()).map(ModuleDescriptor.Exports::source)
                        .collect(Collectors.toSet()));
        // internal, the engine side of units, is for uom-jsr's conversion only
        assertEquals(
                Set.of("org.tinygears.uom.jsr"),
                uom.descriptor().exports().stream().filter(e -> e.source().equals("org.tinygears.uom.internal"))
                        .findFirst().orElseThrow().targets());
        Set<String> packages = new java.util.HashSet<>(api);
        packages.add("org.tinygears.uom.internal");
        assertEquals(packages, uom.descriptor().packages());
        assertTrue(uom.descriptor().requires().stream().noneMatch(r -> r.name().equals("java.measure")));
        assertTrue(uom.descriptor().opens().isEmpty());
        // the engine's helpers are for the two APIs only
        ModuleReference engine = module(Factor.class);
        assertEquals(
                Set.of("org.tinygears.uom.engine", "org.tinygears.uom.engine.parse"),
                engine.descriptor().exports().stream().filter(e -> !e.isQualified())
                        .map(ModuleDescriptor.Exports::source).collect(Collectors.toSet()));
        for (String helper : List.of(
                "org.tinygears.uom.engine.internal",
                "org.tinygears.uom.engine.format",
                "org.tinygears.uom.engine.arithmetic")) {
            assertEquals(
                    Set.of("org.tinygears.uom.jsr", "org.tinygears.uom"),
                    engine.descriptor().exports().stream().filter(e -> e.source().equals(helper)).findFirst()
                            .orElseThrow().targets(),
                    helper);
        }
        assertTrue(engine.descriptor().requires().stream().noneMatch(r -> r.name().equals("java.measure")));
        assertTrue(engine.descriptor().opens().isEmpty());
    }

    @Test
    void onlyTheHelperAndSpiPackagesHavePublicTypesOutsideTheExports() throws Exception {
        List<String> hidden = new ArrayList<>();
        for (ModuleReference m : List
                .of(module(Factor.class), module(org.tinygears.uom.Quantity.class), module(UomUnit.class))) {
            surface(m).stream().filter(l -> l.contains(" hidden ")).forEach(hidden::add);
        }
        assertFalse(hidden.isEmpty());
        for (String line : hidden) {
            assertTrue(
                    line.startsWith("org.tinygears.uom.engine.internal ")
                            || line.startsWith("org.tinygears.uom.engine.arithmetic ")
                            || line.startsWith("org.tinygears.uom.engine.format ")
                            || line.startsWith("org.tinygears.uom.internal ")
                            || line.startsWith("org.tinygears.uom.jsr.spi "),
                    line);
        }
        // The spi package is internal to uom-jsr and holds exactly the provider hooks.
        assertEquals(
                List.of(
                        "org.tinygears.uom.jsr.spi hidden org.tinygears.uom.jsr.spi.Providers",
                        "org.tinygears.uom.jsr.spi hidden org.tinygears.uom.jsr.spi.QuantityFactories",
                        "org.tinygears.uom.jsr.spi hidden org.tinygears.uom.jsr.spi.SystemUnits",
                        "org.tinygears.uom.jsr.spi hidden org.tinygears.uom.jsr.spi.UnitTexts"),
                hidden.stream().filter(l -> l.startsWith("org.tinygears.uom.jsr.spi ")).sorted().toList());
    }

    /** The module whose class path entry holds {@code c}. */
    private static ModuleReference module(Class<?> c) throws URISyntaxException {
        Path location = Path.of(c.getProtectionDomain().getCodeSource().getLocation().toURI());
        return ModuleFinder.of(location).findAll().iterator().next();
    }

    /** Sorted lines: module directives, the API of the exported packages, the public types of the others. */
    private static List<String> surface(ModuleReference ref) throws IOException, ClassNotFoundException {
        ModuleDescriptor d = ref.descriptor();
        String name = d.name();
        Set<String> lines = new TreeSet<>();
        d.requires().stream().filter(r -> !r.name().equals("java.base")).forEach(
                r -> lines.add(
                        name + " module requires "
                                + r.modifiers().stream().map(x -> x.toString().toLowerCase(Locale.ROOT) + " ").sorted()
                                        .collect(Collectors.joining())
                                + r.name()));
        // Exports.toString lists the targets in hash order; sorted, the line is stable.
        d.exports().forEach(
                e -> lines.add(
                        name + " module exports " + e.source()
                                + (e.isQualified() ? " to " + new java.util.TreeSet<>(e.targets()) : "")));
        d.opens().forEach(o -> lines.add(name + " module opens " + o));
        d.provides().forEach(p -> lines.add(name + " module provides " + p));
        Set<String> exported = d.exports().stream().filter(e -> !e.isQualified()).map(ModuleDescriptor.Exports::source)
                .collect(Collectors.toSet());
        List<String> classes;
        try (var reader = ref.open(); Stream<String> s = reader.list()) {
            classes = s
                    .filter(
                            r -> r.endsWith(".class") && !r.contains("$") && !r.endsWith("module-info.class")
                                    && !r.endsWith("package-info.class"))
                    .map(r -> r.substring(0, r.length() - 6).replace('/', '.')).toList();
        }
        for (String className : classes) {
            Class<?> c = Class.forName(className, false, ApiSurfaceTest.class.getClassLoader());
            if (!Modifier.isPublic(c.getModifiers())) {
                continue;
            }
            String pkg = c.getPackageName();
            if (exported.contains(pkg)) {
                type(c, pkg, lines);
            } else {
                lines.add(pkg + " hidden " + c.getName());
            }
        }
        return new ArrayList<>(lines);
    }

    /**
     * {@code c.toGenericString()} with {@code sealed} written the same on every JDK: JDK 25 writes it before the kind of
     * type ("abstract sealed interface"), JDK 17 and 21 leave it out.
     */
    private static String generic(Class<?> c) {
        String s = c.toGenericString().replace("non-sealed ", "").replace("sealed ", "");
        if (!c.isSealed()) {
            return s;
        }
        String kind = c.isAnnotation()
                ? "@interface "
                : c.isInterface() ? "interface " : c.isEnum() ? "enum " : c.isRecord() ? "record " : "class ";
        int at = s.indexOf(kind);
        return s.substring(0, at) + "sealed " + s.substring(at);
    }

    private static void type(Class<?> c, String pkg, Set<String> lines) {
        String prefix = pkg + " " + c.getName().substring(pkg.length() + 1) + " ";
        StringBuilder t = new StringBuilder(generic(c));
        Type superclass = c.getGenericSuperclass();
        if (superclass != null && superclass != Object.class) {
            t.append(" extends ").append(superclass.getTypeName());
        }
        Type[] interfaces = c.getGenericInterfaces();
        if (interfaces.length > 0) {
            t.append(c.isInterface() ? " extends " : " implements ")
                    .append(Arrays.stream(interfaces).map(Type::getTypeName).collect(Collectors.joining(", ")));
        }
        lines.add(prefix + "type " + t);
        List<Member> members = new ArrayList<>();
        members.addAll(List.of(c.getDeclaredConstructors()));
        members.addAll(List.of(c.getDeclaredMethods()));
        members.addAll(List.of(c.getDeclaredFields()));
        for (Member m : members) {
            if (visible(m.getModifiers()) && !m.isSynthetic()) {
                String s = m instanceof Executable e ? e.toGenericString() : ((Field) m).toGenericString();
                lines.add(prefix + "member " + s.replace(" " + c.getName() + ".", " "));
            }
        }
        for (Class<?> nested : c.getDeclaredClasses()) {
            if (visible(nested.getModifiers())) {
                type(nested, pkg, lines);
            }
        }
    }

    private static boolean visible(int modifiers) {
        return Modifier.isPublic(modifiers) || Modifier.isProtected(modifiers);
    }
}
