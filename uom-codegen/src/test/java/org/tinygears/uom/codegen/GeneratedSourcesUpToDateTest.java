    private static Map<String, String> javaFiles(Path dir) throws IOException {
        return files(dir, ".java");
    }

    private static Map<String, String> files(Path dir, String extension) throws IOException {
        Map<String, String> files = new TreeMap<>();
        if (Files.isDirectory(dir)) {
            try (Stream<Path> s = Files.list(dir)) {
                for (Path p : s.filter(p -> p.toString().endsWith(extension)).toList()) {
                    files.put(p.getFileName().toString(), Files.readString(p, StandardCharsets.UTF_8));
                }
            }
        }
        return files;
    }

    /** Problems between generated and committed files; only generated-looking files count as extra. */
    private static List<String> drift(Map<String, String> expected, Path dir) throws IOException {
        Map<String, String> actual = new TreeMap<>(javaFiles(dir));
        actual.putAll(files(dir, ".md"));
        List<String> problems = new ArrayList<>();
        expected.forEach((name, text) -> {
            if (!actual.containsKey(name)) {
                problems.add("missing: " + dir.resolve(name));
            } else if (!actual.get(name).equals(text)) {
                problems.add("differs: " + dir.resolve(name));
            }
        });
        actual.forEach((name, text) -> {
            if (!expected.containsKey(name) && (text.startsWith(Headers.LICENSE + Headers.GENERATED)
                    || text.startsWith("<!-- Generated by uom-codegen"))) {
                problems.add("extra: " + dir.resolve(name));
            }
        });
        return problems;
    }

    @Test
    void committedSourcesMatchTheGenerator() throws IOException {
        Generate.Output out = Generate.generate(DATA);
        List<String> problems = new ArrayList<>(drift(out.quantities(), QUANTITIES));
        problems.addAll(drift(out.systems(), SYSTEMS));
        problems.addAll(drift(out.docs(), DOCS));
        assertTrue(
                problems.isEmpty(),
                () -> "Committed generated sources drift from data/; regenerate with"
                        + " mvn -q -B -Pgenerate -pl uom-codegen -am process-classes\n" + String.join("\n", problems));
    }

    // Standard types share their simple names with the generated types, so only those stay qualified there.
    @Test
    void committedSourcesUseTheirImports() throws IOException {
        Map<String, String> quantities = generatedFiles(QUANTITIES);
        Map<String, String> systems = generatedFiles(SYSTEMS);
        assertEquals(133, quantities.size());
        assertEquals(Set.copyOf(SYSTEMS_FILES), systems.keySet());
        Set<String> packageTypes = quantities.keySet().stream().map(n -> n.substring(0, n.length() - 5))
                .collect(Collectors.toSet());
        List<String> problems = new ArrayList<>();
        quantities.forEach(
                (name, text) -> ImportCheck.problems(text, packageTypes).forEach(p -> problems.add(name + ": " + p)));
        systems.forEach(
                (name, text) -> ImportCheck.problems(text, Set.of()).forEach(p -> problems.add(name + ": " + p)));
        assertEquals(List.of(), problems);
        assertTrue(quantities.get("LengthFactory.java").contains("\nimport javax.measure.Unit;\n"));
        assertTrue(systems.get("SI.java").contains("\nimport javax.measure.quantity.Length;\n"));
    }

    private static Map<String, String> generatedFiles(Path dir) throws IOException {
        Map<String, String> files = javaFiles(dir);
        files.values().removeIf(t -> !t.startsWith(Headers.LICENSE + Headers.GENERATED));
        return files;
    }

