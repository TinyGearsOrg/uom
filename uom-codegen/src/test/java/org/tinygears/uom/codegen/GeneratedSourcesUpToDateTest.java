    @Test
    void driftOfTheUnitTableIsReported() throws IOException {
        Path q = tmp.resolve("q");
        Path sys = tmp.resolve("sys");
        Path docs = Path.of(docs());
        assertEquals(0, generateInto(q, sys).status());
        Path file = docs.resolve("UNITS.md");
        String text = Files.readString(file);
        Map<String, String> expected = Generate.generate(DATA).docs();
        assertEquals(expected, files(docs, ".md"));
        Path old = docs.resolve("OLD.md");
        Path mine = docs.resolve("NOTES.md");
        Files.writeString(file, text.replace("| `ft` |", "| `ft`  |"));
        Files.writeString(old, text);
        Files.writeString(mine, "# Notes\n");
        Run r = check(q, sys);
        assertEquals(1, r.status());
        assertEquals("differs: " + file + "\nstale: " + old + "\n", r.err());
        assertEquals(List.of("differs: " + file, "extra: " + old), drift(expected, docs));
        Files.delete(file);
        r = check(q, sys);
        assertEquals("missing: " + file + "\nstale: " + old + "\n", r.err());
        assertEquals(List.of("missing: " + file, "extra: " + old), drift(expected, docs));
        assertEquals(0, generateInto(q, sys).status());
        assertFalse(Files.exists(old), old.toString());
        assertEquals("# Notes\n", Files.readString(mine));
        assertEquals(text, Files.readString(file));
        assertEquals(0, check(q, sys).status());
    }

