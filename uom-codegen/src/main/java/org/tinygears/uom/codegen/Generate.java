package org.tinygears.uom.codegen;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.PrintStream;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.nio.charset.MalformedInputException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;

import org.tinygears.uom.engine.parse.DefinitionException;
import org.tinygears.uom.engine.parse.DefinitionParser;
import org.tinygears.uom.engine.parse.Definitions;

/**
 * Generates the quantity and catalog sources and the unit table from {@code data/}:
 * {@code [--check] <dataDir> <quantitiesOut> <systemsOut> <docsOut>}.
 */
public final class Generate {
    /** The catalog files, one class each; parents precede dependents and SI comes first. */
    public static final List<String> CATALOGS = List.of(
            "si.units",
            "us-customary.units",
            "imperial.units",
            "cgs.units",
            "cgs-esu.units",
            "cgs-emu.units",
            "cgs-gaussian.units",
            "information.units");
    private static final String TYPES = "quantity-types.txt";
    // Only files with the generated line (Markdown: MD_HEADER) count as stale; hand-written files stay.
    private static final String MD_HEADER = "<!-- Generated by uom-codegen";
    private static final String USAGE = "usage: Generate [--check] <dataDir> <quantitiesOut> <systemsOut> <docsOut>";

    /** File name to source text for each output directory, sorted by name. */
    public record Output(Map<String, String> quantities, Map<String, String> systems, Map<String, String> docs) {}

    private Generate() {
    }

    /**
     * Runs {@link #run} and throws if it fails, so that {@code exec:java} ends with a BUILD FAILURE; the messages are
     * already printed.
     */
    public static void main(String[] args) {
        int status = run(args, System.err);
        if (status != 0) {
            throw new IllegalStateException("generation failed with status " + status);
        }
    }

    /** Returns 0 on success, 1 on a generation error or a {@code --check} difference, 2 on a usage error. */
    public static int run(String[] args, PrintStream err) {
        boolean check = args.length == 5 && args[0].equals("--check");
        if (!check && (args.length != 4 || args[0].startsWith("--"))) {
            err.println(USAGE);
            return 2;
        }
        int i = check ? 1 : 0;
        Path dataDir = Path.of(args[i]);
        Path quantitiesOut = Path.of(args[i + 1]);
        Path systemsOut = Path.of(args[i + 2]);
        Path docsOut = Path.of(args[i + 3]);
        try {
            Output out = generate(dataDir);
            refuseHandWritten(out.quantities(), quantitiesOut);
            refuseHandWritten(out.systems(), systemsOut);
            refuseHandWritten(out.docs(), docsOut);
            if (check) {
                List<String> problems = new ArrayList<>(differences(out.quantities(), quantitiesOut));
                problems.addAll(differences(out.systems(), systemsOut));
                problems.addAll(differences(out.docs(), docsOut));
                problems.forEach(err::println);
                return problems.isEmpty() ? 0 : 1;
            }
            write(out.quantities(), quantitiesOut);
            write(out.systems(), systemsOut);
            write(out.docs(), docsOut);
            return 0;
        } catch (GenerationException e) {
            Throwable cause = e.getCause() instanceof UncheckedIOException u ? u.getCause() : e.getCause();
            err.println(cause instanceof IOException io ? e.getMessage() + " (" + io + ")" : e.getMessage());
            return 1;
        } catch (IOException e) {
            err.println(e);
            return 1;
        } catch (UncheckedIOException e) {
            err.println(e.getCause());
            return 1;
        }
    }

    /**
     * The files generated from {@code dataDir}. The Java sources are not formatted: Spotless formats them, as it formats
     * the hand-written ones, so compare them with {@link #sameCode} and not with {@code equals}.
     */
    public static Output generate(Path dataDir) {
        Map<String, Definitions> parsed = catalogs(dataDir);
        Definitions si = parsed.get(CATALOGS.get(0));
        List<QuantityTypeSpec> specs = types(dataDir, si);
        Map<String, String> files = new TreeMap<>();
        for (QuantityTypeSpec s : specs) {
            files.put(s.name() + ".java", SourceEmitter.typedInterface(s));
            files.put(s.name() + "Double.java", SourceEmitter.doubleImplementation(s));
            files.put(s.name() + "Decimal.java", SourceEmitter.decimalImplementation(s));
            files.put(s.name() + "Factory.java", SourceEmitter.factory(s, si));
        }
        files.put("QuantityTypes.java", SourceEmitter.registry(specs));
        Map<String, String> systems = new TreeMap<>();
        Map<String, CatalogBuilder.Catalog> catalogs = CatalogBuilder.catalogs(parsed, specs);
        // The first catalog (SI) also gets a constant for each system unit that has no definition (m/s).
        List<QuantityTypeSpec> unnamed = specs.stream().filter(QuantityTypeSpec::explicit).toList();
        catalogs.forEach(
                (file, c) -> systems.put(
                        c.className() + ".java",
                        CatalogEmitter
                                .catalog(c, parsed.get(file), file.equals(CATALOGS.get(0)) ? unnamed : List.of())));
        return new Output(
                Collections.unmodifiableMap(files),
                Collections.unmodifiableMap(systems),
                Map.of("UNITS.md", UnitTableEmitter.table(catalogs, specs)));
    }

    /** The catalog files parsed, in {@link #CATALOGS} order. */
    static Map<String, Definitions> catalogs(Path dataDir) {
        Map<String, Definitions> parsed = new LinkedHashMap<>();
        for (String file : CATALOGS) {
            parsed.put(file, parse(dataDir, file));
        }
        return parsed;
    }

    /** The quantity types of {@code data/quantity-types.txt}, evaluated in the SI definitions. */
    static List<QuantityTypeSpec> types(Path dataDir, Definitions si) {
        List<QuantityTypeSpec> specs;
        try (Reader in = open(dataDir, TYPES)) {
            specs = QuantityTypesParser.parse(TYPES, in, si);
        } catch (IOException | UncheckedIOException e) {
            throw new GenerationException(TYPES, 0, "cannot read " + TYPES, e);
        }
        if (specs.isEmpty()) {
            throw new GenerationException(TYPES, 0, "no quantity types defined");
        }
        return specs;
    }

    static Definitions parse(Path dataDir, String file) {
        try (Reader in = open(dataDir, file)) {
            return DefinitionParser.parse(file, in, name -> open(dataDir, name));
        } catch (DefinitionException e) {
            String prefix = e.source() + ":" + e.line() + ": ";
            throw new GenerationException(e.source(), e.line(), e.getMessage().substring(prefix.length()), e);
        } catch (IOException | UncheckedIOException e) {
            throw new GenerationException(file, 0, "cannot read " + file, e);
        }
    }

    static Reader open(Path dataDir, String name) throws IOException {
        return Files.newBufferedReader(dataDir.resolve(name), StandardCharsets.UTF_8);
    }

    static List<String> differences(Map<String, String> files, Path outDir) throws IOException {
        List<String> problems = new ArrayList<>();
        for (Map.Entry<String, String> f : files.entrySet()) {
            Path p = outDir.resolve(f.getKey());
            if (!Files.isRegularFile(p)) {
                problems.add("missing: " + p);
            } else if (!same(f.getKey(), f.getValue(), Files.readString(p, StandardCharsets.UTF_8))) {
                problems.add("differs: " + p);
            }
        }
        for (Path p : stale(files, outDir)) {
            problems.add("stale: " + p);
        }
        return problems;
    }

    /** A Java source is the same if it differs only in whitespace, which is Spotless's to decide; a document must be equal. */
    private static boolean same(String name, String generated, String committed) {
        return name.endsWith(".java") ? sameCode(generated, committed) : generated.equals(committed);
    }

    /**
     * Whether two Java sources agree in everything but whitespace. The generator does not format its output, Spotless
     * does, so a committed file and a fresh generation differ in layout only.
     */
    static boolean sameCode(String generated, String committed) {
        return withoutWhitespace(generated).equals(withoutWhitespace(committed));
    }

    private static String withoutWhitespace(String text) {
        return text.replaceAll("\\s+", "");
    }

    /** A target that exists and is not generated-looking is hand-written and must not be overwritten. */
    static void refuseHandWritten(Map<String, String> files, Path outDir) throws IOException {
        for (String name : files.keySet()) {
            Path p = outDir.resolve(name);
            if (Files.isRegularFile(p) && !isGenerated(p)) {
                throw new GenerationException(p.toString(), 0, "refusing to overwrite a hand-written file");
            }
        }
    }

    static void write(Map<String, String> files, Path outDir) throws IOException {
        Files.createDirectories(outDir);
        for (Map.Entry<String, String> f : files.entrySet()) {
            Files.write(outDir.resolve(f.getKey()), f.getValue().getBytes(StandardCharsets.UTF_8));
        }
        for (Path p : stale(files, outDir)) {
            Files.delete(p);
        }
    }

    /** Generated-looking files in {@code outDir} that are no longer generated; others are kept. */
    private static List<Path> stale(Map<String, String> files, Path outDir) throws IOException {
        if (!Files.isDirectory(outDir)) {
            return List.of();
        }
        try (Stream<Path> s = Files.list(outDir)) {
            List<Path> result = new ArrayList<>();
            for (Path p : s.sorted().toList()) {
                String name = p.getFileName().toString();
                if (!files.containsKey(name) && Files.isRegularFile(p) && isGenerated(p)) {
                    result.add(p);
                }
            }
            return result;
        }
    }

    /**
     * A {@code *.java} file whose leading comment lines are followed by {@link Headers#GENERATED} (the license header
     * of the generator, or the former single SPDX line), or a {@code *.md} file starting with {@code MD_HEADER}.
     */
    private static boolean isGenerated(Path p) throws IOException {
        String name = p.getFileName().toString();
        if (!name.endsWith(".java") && !name.endsWith(".md")) {
            return false;
        }
        try (BufferedReader in = Files.newBufferedReader(p, StandardCharsets.UTF_8)) {
            String first = in.readLine();
            if (name.endsWith(".md")) {
                return first != null && first.startsWith(MD_HEADER);
            }
            for (String line = first; line != null; line = in.readLine()) {
                if (line.startsWith(Headers.GENERATED)) {
                    return true;
                }
                if (!line.isEmpty() && !line.startsWith("//") && !line.startsWith("/*") && !line.startsWith(" *")) {
                    return false;
                }
            }
            return false;
        } catch (MalformedInputException e) {
            return false;
        }
    }
}
